const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const ts=require('../frontend/node_modules/typescript');
const memory=new Map();
const context=vm.createContext({exports:{},localStorage:{getItem:key=>memory.get(key)||null,setItem:(key,value)=>memory.set(key,value)}});
vm.runInContext(ts.transpileModule(fs.readFileSync('frontend/src/ui-state.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,context);
const ui=context.exports;
assert.equal(ui.sameFilters({q:' Buyer ',name:'saved view'},{...ui.FILTER_DEFAULTS,q:'Buyer'}),true);
assert.equal(ui.sameFilters({has_email:true},{has_email:false}),false);
assert.deepEqual(Array.from(ui.filterChips({q:'Buyer',has_email:true},{},{}),x=>x.key),['q','has_email']);
assert.equal(ui.formatDate('broken timestamp'),'日期待核实');
assert.equal(ui.formatDate(null),'未提供');
ui.writeTablePreferences({density:'compact',columns:['location','unknown','location']});
assert.equal(ui.readTablePreferences().density,'compact');
assert.deepEqual(Array.from(ui.readTablePreferences().columns),['company','location','action']);
memory.set('voken-workbench-display-v1','invalid JSON');
assert.deepEqual(Array.from(ui.readTablePreferences().columns),Array.from(ui.DEFAULT_COLUMNS));
context.localStorage.getItem=()=>{throw Error('storage unavailable');};
context.localStorage.setItem=()=>{throw Error('storage unavailable');};
assert.equal(ui.readTablePreferences().density,'comfortable');
assert.doesNotThrow(()=>ui.writeTablePreferences({density:'compact',columns:[]}));
console.log('Passed applied/draft filters, chip mapping, invalid dates, display preferences and unavailable storage.');
